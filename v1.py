books = []

print("=== Мой список книг ===")

while True:
    # Пользователь вводит название
    book = input("\nВведите название книги (или 'выход' для завершения): ")
    
    # Проверка на выход из программы
    if book.lower() == 'выход':
        print("До встречи!")
        break
        
    # Добавляем книгу в список и показываем результат
    books.append(book)
    print("\nТекущий список книг:")
    for item in books:
        print(f"- {item}")